"""results/routed.csv -> results/routed.md: worst case per group (rate, corner, direction) and the weakest nets."""
import csv, os, collections

HERE = os.path.dirname(os.path.abspath(__file__))
rows = list(csv.DictReader(open(os.path.join(HERE, 'results', 'routed.csv'))))
errs = [r for r in rows if r.get('error')]
rows = [r for r in rows if not r.get('error')]
for r in rows:
    for k in ('eh_mV', 'ew_mask_ps', 'v_margin_mV', 't_margin_ps', 'vmax_mV', 'vmin_mV', 'delay_ps'):
        r[k] = float(r[k]) if r[k] not in ('', 'nan') else float('nan')
    r['limits_ok'] = r['limits_ok'] == 'True'
    rate, corner, *rest = r['point'].split('_')
    r['rate'], r['corner'], r['case'] = rate[1:], corner, '_'.join(rest)

fmt = lambda v: 'nan' if v != v else f'{v:.0f}'
out = ['# LPDDR4 SI of the routed nets', '',
       'Generated by `routed_si.py` + `routed_report.py` from the board copper (`extract_routes.py`). Worst of U12/U7 '
       'ball and die per row. Margins are SI only (reflections, ISI, package, buffer edges): jitter, crosstalk, SSO and '
       'the timing budgets still have to fit inside them. Masks and limits: README.md. min/max: the corner model files '
       '(`corner_models.py`) simulated at typ.' + (f' **{len(errs)} netlist row(s) failed to run** (error column of '
       'routed.csv).' if errs else ''), '',
       '| MT/s | corner | case | nets | min eye height (mV) | min V margin (mV) | min t margin (ps) | Vmax (mV) | Vmin (mV) | '
       'limits | weakest net |', '|---|---|---|---|---|---|---|---|---|---|---|']
grp = collections.defaultdict(list)
for r in rows: grp[(r['rate'], r['corner'], r['case'])].append(r)
order = {'typ': 0, 'min': 1, 'max': 2}
for (rate, corner, case), rs in sorted(grp.items(), key=lambda kv: (kv[0][0], order[kv[0][1]], kv[0][2])):
    w = min(rs, key=lambda r: r['v_margin_mV'])
    out.append(f"| {rate} | {corner} | {case} | {len({r['net'] for r in rs})} | {fmt(min(r['eh_mV'] for r in rs))} | "
               f"{fmt(w['v_margin_mV'])} | {fmt(min(r['t_margin_ps'] for r in rs))} | "
               f"{fmt(max(r['vmax_mV'] for r in rs))} | {fmt(min(r['vmin_mV'] for r in rs))} | "
               f"{'OK' if all(r['limits_ok'] for r in rs) else '**FAIL**'} | {w['net']} ({w['where']}) |")
bad = [r for r in rows if r['v_margin_mV'] < 0 or r['t_margin_ps'] != r['t_margin_ps'] or r['t_margin_ps'] < 0
       or not r['limits_ok']]
out += ['', f'Rows with a negative margin or a limit violation: {len(bad)}.']
if bad:
    out += ['', '| point | net | where | V margin | t margin | Vmax | Vmin |', '|---|---|---|---|---|---|---|']
    out += [f"| {r['point']} | {r['net']} | {r['where']} | {fmt(r['v_margin_mV'])} | {fmt(r['t_margin_ps'])} | "
            f"{fmt(r['vmax_mV'])} | {fmt(r['vmin_mV'])} |" for r in bad[:60]]
# weakest nets at 1600 typ, per kind
out += ['', '## Weakest nets, 1600 MT/s, all corners (die)', '',
        '| kind | net | worst V margin (mV) | worst t margin (ps) | at |', '|---|---|---|---|---|']
by = collections.defaultdict(list)
for r in rows:
    if r['rate'] == '1600' and r['where'] == 'die': by[(r['kind'], r['net'])].append(r)
for kind in ('dq_write', 'dq_read', 'ca'):
    nets = sorted(((min(x['v_margin_mV'] for x in v), n, v) for (k, n), v in by.items() if k == kind))[:5]
    for vm, n, v in nets:
        w = min(v, key=lambda x: x['v_margin_mV'])
        out.append(f"| {kind} | {n} | {fmt(vm)} | {fmt(min(x['t_margin_ps'] for x in v))} | {w['point']} |")
open(os.path.join(HERE, 'results', 'routed.md'), 'w').write('\n'.join(out) + '\n')
print('\n'.join(out))
